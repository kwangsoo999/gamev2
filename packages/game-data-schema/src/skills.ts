function enrichSkillDefinition(s: SkillDefinition): SkillDefinition {
  const enriched: SkillDefinition = {
    ...s,
    maxLevel: s.maxLevel && s.maxLevel > 5 ? s.maxLevel : 10,
    executionType: s.executionType || inferExecutionType(s),
    hitCount: s.hitCount ?? 1,
    areaRadius: s.areaRadius ?? s.hitbox?.widthPx ?? 95,
    targetLimit: s.targetLimit ?? (s.targetType === 'aoe' ? 8 : 1),
    baseDamage: s.baseDamage ?? Math.round((s.damageMultiplier || 0) * 100),
    damageScaling: s.damageScaling ?? (s.upgradeScaling?.powerPerLevelPct ?? 15) / 100,
    attackPowerCoefficient:
      s.attackPowerCoefficient ?? (s.damageType === 'magic' ? 0 : s.damageMultiplier || 0),
    magicPowerCoefficient:
      s.magicPowerCoefficient ?? (s.damageType === 'magic' ? s.damageMultiplier || 0 : 0),
    castTimeMs: s.castTimeMs ?? Math.round((s.castTime || 0) * 1000),
    animationId: s.animationId || s.animation || `anim_${s.id}`,
    vfxId: s.vfxId || s.vfxKey,
    masteryConfig: s.masteryConfig || { ...DEFAULT_SKILL_MASTERY_CONFIG },
    pveModifier: s.pveModifier ?? 1.0,
    pvpModifier: s.pvpModifier ?? 0.92,
    bossModifier: s.bossModifier ?? 1.0,
    animationMetadata: s.animationMetadata || resolveSkillAnimationMetadata(s),
  };
  enriched.evolutionMilestones =
    s.evolutionMilestones && s.evolutionMilestones.length > 0
      ? s.evolutionMilestones
      : buildEvolutionMilestonesForSkill(enriched);
  return enriched;
}

